export function translateData<T>(value: T, lang: Lang): T {
  if (lang === 'id') return value;
  if (typeof value === 'string') return (EN[value] ?? value) as T;
  if (Array.isArray(value)) return value.map((v) => translateData(v, lang)) as T;
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, translateData(v, lang)])) as T;
  }
  return value;
}
